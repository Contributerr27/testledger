def git(*args: str, env_date: datetime | None = None) -> None:
    env = None
    if env_date:
        import os

        env = os.environ | {
            "GIT_AUTHOR_DATE": env_date.isoformat(),
            "GIT_COMMITTER_DATE": env_date.isoformat(),
        }
    subprocess.run(["git", "-C", str(TARGET), *args], check=True, capture_output=True, env=env)


def junit_xml(run_dir: Path, results: list[tuple[str, str, str, float, bool]]) -> None:
    by_suite: dict[str, list] = {}
    for test_id, suite, file, dur, failed in results:
        by_suite.setdefault(suite, []).append((test_id.rsplit(".", 1)[1], file, dur, failed))
    parts = ['<?xml version="1.0" encoding="UTF-8"?>', "<testsuites>"]
    for suite, cases in by_suite.items():
        parts.append(
            f'  <testsuite name="{suite}" tests="{len(cases)}" failures="{sum(c[3] for c in cases)}">'
        )
        for name, file, dur, failed in cases:
            parts.append(f'    <testcase classname="{suite}" name="{name}" file="{file}" time="{dur:.3f}">')
            if failed:
                parts.append(
                    '      <failure message="AssertionError: expected &lt;200&gt; but was &lt;500&gt;"/>'
                )
            parts.append("    </testcase>")
        parts.append("  </testsuite>")
    parts.append("</testsuites>")
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "TEST-results.xml").write_text("\n".join(parts), encoding="utf-8")


def cucumber_json(run_dir: Path, results: list[tuple[str, str, str, float, bool]]) -> None:
    features: dict[str, dict] = {}
    for sid, feature, uri, dur, failed in results:
        f = features.setdefault(feature, {"name": feature, "uri": uri, "elements": []})
        f["elements"].append(
            {
                "id": sid,
                "name": sid.split(";")[1].replace("-", " "),
                "type": "scenario",
                "tags": [{"name": "@ui"}],
                "steps": [
                    {
                        "name": "Given I am on the site",
                        "result": {"status": "passed", "duration": int(dur * 0.2e9)},
                    },
                    {
                        "name": "When I complete the flow",
                        "result": {
                            "status": "failed" if failed else "passed",
                            "duration": int(dur * 0.8e9),
                            **(
                                {"error_message": "TimeoutException: element not clickable"} if failed else {}
                            ),
                        },
                    },
                ],
            }
        )
    (run_dir / "cucumber.json").write_text(json.dumps(list(features.values()), indent=1), encoding="utf-8")


def main() -> None:
    if TARGET.exists():
        import shutil

        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)
    write_sources()
    git("init", "-q", "-b", "main")
    git("config", "user.email", "demo@example.com")
    git("config", "user.name", "Demo")
    start = datetime.now(tz=UTC) - timedelta(days=84)
    git("add", "-A")
    git("commit", "-q", "-m", "Initial test estate", env_date=start)

    ci = TARGET / "ci-reports"
    run_no = 0
    for week in range(12):
        for day in range(0, 7, 2):  # ~3 runs a week
            ts = start + timedelta(days=week * 7 + day, hours=10)
            run_no += 1
            sha = f"{random.getrandbits(40):010x}"
            genuine_fail = {
                t for t, *_ in TESTS if week in TESTS[[x[0] for x in TESTS].index(t)][5] and day == 0
            }
            genuine_fail |= {
                t for t, *_ in CUCUMBER if week in CUCUMBER[[x[0] for x in CUCUMBER].index(t)][5] and day == 0
            }
            # product change to make the SHA real
            (TARGET / "src/main/java/com/acme/OrderService.java").write_text(
                f"public class OrderService {{ // rev {run_no}\n}}\n", encoding="utf-8"
            )
            git("add", "-A")
            git("commit", "-q", "-m", f"feat: order flow change {run_no}", env_date=ts)
            sha_real = subprocess.run(
                ["git", "-C", str(TARGET), "rev-parse", "--short=10", "HEAD"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout.strip()
            sha = sha_real

            # attempt 1
            flaky_now: set[str] = set()
            jres, cres = [], []
            for test_id, suite, file, dur, flake, _ in TESTS:
                f = test_id in genuine_fail or (random.random() < flake)
                if f and test_id not in genuine_fail:
                    flaky_now.add(test_id)
                jres.append((test_id, suite, file, dur * random.uniform(0.8, 1.2), f))
            for sid, feature, uri, dur, flake, _ in CUCUMBER:
                f = sid in genuine_fail or (random.random() < flake)
                if f and sid not in genuine_fail:
                    flaky_now.add(sid)
                cres.append((sid, feature, uri, dur * random.uniform(0.8, 1.2), f))
            d1 = ci / f"{ts:%Y%m%d}-{sha}-attempt1"
            junit_xml(d1, jres)
            cucumber_json(d1, cres)
            # rerun if anything failed (flaky clears, genuine stays)
            if flaky_now or genuine_fail:
                d2 = ci / f"{ts:%Y%m%d}-{sha}-attempt2"
                junit_xml(d2, [(t, s, f, d, (t in genuine_fail)) for t, s, f, d, _ in jres])
                cucumber_json(d2, [(t, s, f, d, (t in genuine_fail)) for t, s, f, d, _ in cres])
            # genuine failure -> fix commit next day
            if genuine_fail:
                (TARGET / "src/main/java/com/acme/PriceCalculator.java").write_text(
                    f"public class PriceCalculator {{ // fix {run_no}\n}}\n", encoding="utf-8"
                )
                git("add", "-A")
                git(
                    "commit",
                    "-q",
                    "-m",
                    f"fix: regression in pricing/order path (#{run_no})",
                    env_date=ts + timedelta(days=1),
                )
            # maintenance churn on the brittle Selenium test every other week
            if week % 2 == 0:
                p = TARGET / "src/test/java/com/acme/ui/CheckoutSeleniumTest.java"
                p.write_text(
                    p.read_text(encoding="utf-8") + f"// locator tweak {run_no}\n" * 6, encoding="utf-8"
                )
                git("add", "-A")
                git(
                    "commit",
                    "-q",
                    "-m",
                    f"test: update checkout locators {run_no}",
                    env_date=ts + timedelta(hours=3),
                )

    (TARGET / "testledger.yml").write_text(
        """org_name: Acme Commerce (demo)
window_days: 90
rates:
  engineer_hourly_usd: 75
  ci_minute_usd: 0.008
  triage_minutes_per_false_alarm: 18
  maintenance_minutes_per_line: 1.5
  regression_value_usd: 2000
sources:
  junit_globs: ["ci-reports/**/TEST-*.xml"]
  cucumber_globs: ["ci-reports/**/cucumber.json"]
  git_repo: "."
""",
        encoding="utf-8",
    )
    (TARGET / "mutation.json").write_text(
        json.dumps(
            {"RecommendationService.java": 0.21, "PriceCalculator.java": 0.88, "OrderService.java": 0.74}
        ),
        encoding="utf-8",
    )
    print(
        f'Demo estate written to {TARGET}\nNext: cd "{TARGET}" && testledger analyze --config testledger.yml --reports . --mutation mutation.json --out reports'
    )


if __name__ == "__main__":
    main()
